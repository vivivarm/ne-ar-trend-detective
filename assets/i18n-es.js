(function(){
  const ES=window.NEAR_ES, orig=new WeakMap(), origAttr=new WeakMap(), ATTRS=['placeholder','aria-label','title'];
  let on=false, busy=false;
  const tr=s=>{ const k=s.trim().replace(/\s+/g,' '); if(!k) return null; if(ES.EXACT[k]!=null) return ES.EXACT[k];
    for(const [re,rep] of ES.PATTERNS){ if(re.test(k)) return k.replace(re,rep); } return null; };
  const skip=el=>!el||/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/.test(el.tagName)||el.closest('[data-no-i18n],.ma-msgs,.ma-out');
  function doNode(n){ if(skip(n.parentElement)) return; const src=orig.has(n)?orig.get(n):n.nodeValue; const t=tr(src); if(t==null) return;
    if(!orig.has(n)) orig.set(n,n.nodeValue); const lead=src.match(/^\s*/)[0], trail=src.match(/\s*$/)[0]; const v=lead+t+trail; if(n.nodeValue!==v) n.nodeValue=v; }
  function doEl(el){ if(skip(el)) return; ATTRS.forEach(a=>{ if(!el.hasAttribute(a)) return; const m=origAttr.get(el)||{}; const src=a in m?m[a]:el.getAttribute(a); const t=tr(src); if(t==null) return; m[a]=src; origAttr.set(el,m); if(el.getAttribute(a)!==t) el.setAttribute(a,t); }); }
  function walk(root){ if(root.nodeType===3){ doNode(root); return; } if(root.nodeType!==1) return; doEl(root);
    const w=document.createTreeWalker(root,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT); let n; while(n=w.nextNode()){ n.nodeType===3?doNode(n):doEl(n); } }
  function restore(){ const w=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT); let n;
    while(n=w.nextNode()){ if(n.nodeType===3){ if(orig.has(n)){ n.nodeValue=orig.get(n); orig.delete(n); } } else { const m=origAttr.get(n); if(m){ for(const a in m) n.setAttribute(a,m[a]); origAttr.delete(n); } } } }
  const mo=new MutationObserver(ms=>{ if(!on||busy) return; busy=true; try{ for(const m of ms){ if(m.type==='characterData'){ orig.delete(m.target); doNode(m.target); } else if(m.type==='attributes'){ const o=origAttr.get(m.target); if(o) delete o[m.attributeName]; doEl(m.target); } else m.addedNodes.forEach(walk); } } finally{ busy=false; } });
  function set(lang){ on=lang==='es'; document.documentElement.lang=on?'es':'en'; try{ localStorage.setItem('near-lang',lang); }catch(e){}
    document.querySelectorAll('[data-lang-btn]').forEach(b=>{ b.textContent=on?'EN':'ES'; b.setAttribute('aria-label',on?'Switch to English':'Cambiar a español'); b.title=on?'English':'Español'; });
    if(on){ busy=true; walk(document.body); busy=false; mo.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:ATTRS}); }
    else { mo.disconnect(); restore(); } }
  window.nearSetLang=set;
  document.addEventListener('click',e=>{ const b=e.target.closest('[data-lang-btn]'); if(b){ e.preventDefault(); set(on?'en':'es'); } });
  let start='en'; try{ const q=new URLSearchParams(location.search).get('lang'); start=q||localStorage.getItem('near-lang')||'en'; }catch(e){}
  if(start==='es') (document.readyState==='loading'?addEventListener('DOMContentLoaded',()=>set('es')):set('es'));
})();
